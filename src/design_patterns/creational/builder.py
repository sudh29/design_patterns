# 4. Driver / Demonstration
# ==============================================================================
if __name__ == "__main__":
    builder = ConcreteHttpRequestBuilder()
    director = RequestDirector(builder)

    print("=== Standard Recipe from Director ===")
    get_req = director.construct_json_get("https://api.github.com/zen")
    print(f"Constructed: {get_req.method} {get_req.url} (Headers: {get_req.headers})")

    post_req = director.construct_json_post(
        "https://api.github.com/repos", {"name": "design_patterns"}
    )
    print(f"Constructed: {post_req.method} {post_req.url} (Body: {post_req.body!r})")

    print("\n=== Custom Fluent Construction ===")
    custom_req = (
        builder.set_url("https://auth.company.com/oauth/token")
        .set_method("POST")
        .add_header("Authorization", "Bearer secret-token")
        .set_timeout(10.0)
        .set_max_retries(5)
        .build()
    )
    print(f"Custom: {custom_req.method} {custom_req.url} (Timeout: {custom_req.timeout}s)")
